/// Compiles one `.gogo` file; `uses` paths resolve relative to it.
pub fn compile_file(path: &Path) -> Result<Compiled, String> {
    let source = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let dir: PathBuf = path.parent().map(Path::to_path_buf).unwrap_or_default();
    let loader = move |rel: &str| std::fs::read_to_string(dir.join(rel)).ok();
    Ok(compile(&source, &loader))
}

/// A file is a page when a `View`/`Panel` root opens a line at column 0;
/// fragment files (themes, widgets) and test fixtures with another root
/// are skipped with a note.
fn is_page(source: &str) -> bool {
    source.lines().any(|l| l.starts_with("View ") || l.starts_with("View{") || l == "View" || l.starts_with("Panel ") || l.starts_with("Panel{") || l == "Panel")
}

/// For `build.rs`: compiles every `*.gogo` in `dir` into one Rust file at
/// `out` (one `pub mod <file stem>` each), plus `PAGES` (name → page) and
/// the asset tables: every image/font path a page names, embedded from
/// `res_root` (`res://x` = `res_root/x`) — a missing file fails the build.
/// Errors are returned as one string for `panic!` — a bad page fails the
/// build with file:line.
pub fn build_pages(dir: &Path, out: &Path, res_root: &Path) -> Result<(), String> {
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?.filter_map(|e| e.ok().map(|e| e.path())).filter(|p| p.extension().map(|x| x == "gogo").unwrap_or(false)).collect();
    entries.sort();
    let mut source = String::from("// Generated by gogo::build_pages — do not edit.\n");
    let mut errors = String::new();
    let mut modules: Vec<String> = Vec::new();
    let mut images: Vec<String> = Vec::new();
    let mut fonts: Vec<String> = Vec::new();
    for path in &entries {
        let module = path.file_stem().and_then(|s| s.to_str()).unwrap_or("page").replace('-', "_");
        let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        if !is_page(&text) {
            println!("cargo:warning={}: not a page (no View/Panel root) — skipped", path.display());
            continue;
        }
        let compiled = compile_file(path)?;
        for s in &compiled.page.strings {
            let lower = s.to_ascii_lowercase();
            if lower.ends_with(".png") || lower.ends_with(".jpg") || lower.ends_with(".jpeg") {
                if !images.contains(s) {
                    images.push(s.clone());
                }
            } else if lower.ends_with(".ttf") || lower.ends_with(".otf") {
                if !fonts.contains(s) {
                    fonts.push(s.clone());
                }
            }
        }
        modules.push(module.clone());
        for d in &compiled.diags {
            let line = format!("{}:{}: {} {}: {}\n", path.display(), d.line, if d.severity == Severity::Error { "error" } else { "warning" }, d.code, d.message);
            if d.severity == Severity::Error {
                errors.push_str(&line);
            } else {
                println!("cargo:warning={}", line.trim_end());
            }
        }
        println!("cargo:rerun-if-changed={}", path.display());
        source.push_str(&emit::emit_rust(&compiled.page, &module));
        source.push('\n');
    }
    // Every page by file stem, for a `--page <stem>` pick at runtime.
    source.push_str("/// (file stem, page) for every page in `ui/`.\npub static PAGES: &[(&str, &gogo::page::StaticPage)] = &[\n");
    for m in &modules {
        source.push_str(&format!("    ({m:?}, &{m}::PAGE),\n"));
    }
    source.push_str("];\n\n");
    // Asset tables: the key is the path as the file wrote it.
    let table = |name: &str, doc: &str, keys: &[String], errors: &mut String| -> String {
        let mut t = format!("/// {doc}\npub const {name}: &[(&str, &[u8])] = &[\n");
        for key in keys {
            let rel = key.strip_prefix("res://").unwrap_or(key);
            let file = res_root.join(rel);
            if !file.is_file() {
                errors.push_str(&format!("asset `{key}` not found at {}\n", file.display()));
                continue;
            }
            // A `.ignore` file in a folder (or any folder above it, under
            // the root) keeps that folder out of the build: art that is not
            // shipped yet (assets/Images/RealObjects, Stickers). Only named
            // assets embed anyway, so the fence is an ERROR on a page that
            // names one — the file says "not yet"; a silent embed would ship
            // 40 MB nobody decided on.
            if let Some(ignore) = ignore_file_above(&file, res_root) {
                errors.push_str(&format!("asset `{key}` sits under {} — delete the .ignore to ship that folder\n", ignore.display()));
                continue;
            }
            let abs = file.canonicalize().unwrap_or(file).display().to_string().trim_start_matches("\\\\?\\").to_string();
            t.push_str(&format!("    ({key:?}, include_bytes!({abs:?})),\n"));
        }
        t.push_str("];\n\n");
        t
    };
    // The default face first (the first entry is what text falls back to).
    fonts.sort_by_key(|f| (!f.contains("Roboto Regular"), f.clone()));
    source.push_str(&table("FONTS", "(key, TTF bytes) for every font a page names; the first is the default face.", &fonts, &mut errors));
    source.push_str(&table("IMAGES", "(key, encoded image bytes) for every image a page names.", &images, &mut errors));
    if !errors.is_empty() {
        return Err(errors);
    }
    std::fs::write(out, source).map_err(|e| format!("{}: {e}", out.display()))
}

/// The nearest `.ignore` file in `file`'s folder or its parents, stopping
/// at `root` (`None` = not ignored).
fn ignore_file_above(file: &Path, root: &Path) -> Option<PathBuf> {
    let root = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
    let mut dir = file.canonicalize().ok()?;
    dir.pop();
    loop {
        let candidate = dir.join(".ignore");
        if candidate.is_file() {
            // Without the `\\?\` verbatim prefix canonicalize adds on Windows.
            let shown = candidate.display().to_string();
            return Some(PathBuf::from(shown.trim_start_matches("\\\\?\\")));
        }
        if dir == root || !dir.pop() {
            return None;
        }
    }
}
